/**
 * Enrich dashboard metrics with targets
 * This is the main function called by the dashboard
 */
export const getDashboardTargets = async (year, month, currentMetrics = {}) => {
  // Get business target (with auto-fallback)
  const businessTarget = await getOrCreateBusinessTarget(
    year, 
    month, 
    currentMetrics.previousRevenue
  );
  
  // Get staff targets
  let staffTargets = [];
  try {
    staffTargets = await fetchAllUserTargets(year, month);
  } catch (e) {
    // Use defaults
  }
  
  return {
    // Main targets
    targetRevenue: businessTarget.target_revenue,
    targetGrossMargin: businessTarget.target_gross_margin,
    targetCashReserveDays: businessTarget.target_cash_reserve_days,
    targetOutstandingRatio: businessTarget.max_outstanding_ratio,
    
    // Staff defaults
    defaultStaffTargetRevenue: businessTarget.default_staff_target_revenue,
    
    // Staff-specific targets (map by user_id)
    staffTargetsMap: staffTargets.reduce((acc, t) => {
      acc[t.user_id] = t;
      return acc;
    }, {}),
    
    // Metadata
    isAutoGenerated: businessTarget.isAutoGenerated,
    isUnsaved: businessTarget.isUnsaved,
    
    // Calculated gaps
    revenueGap: Math.max(0, businessTarget.target_revenue - (currentMetrics.totalRevenue || 0)),
    marginGap: (businessTarget.target_gross_margin || 35) - (currentMetrics.grossMargin || 0),
  };
};

