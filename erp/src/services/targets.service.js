// ==========================================
// FALLBACK CALCULATION HELPERS
// ==========================================

/**
 * Calculate fallback target based on previous month's actuals
 * Returns target = previous_month * 1.10 (10% growth)
 */
const calculateFallbackTarget = async (year, month, knownPreviousRevenue = null) => {
  // Calculate previous month
  let prevYear = year;
  let prevMonth = month - 1;
  
  if (prevMonth === 0) {
    prevMonth = 12;
    prevYear = year - 1;
  }
  
  let previousRevenue = knownPreviousRevenue;
  let previousMargin = 35;
  
  // Try to get actual previous month data
  if (!previousRevenue) {
    try {
      // Get previous month's actual revenue from reports
      const { data: prevTarget } = await api.get(`/targets/business/${prevYear}/${prevMonth}`);
      previousRevenue = prevTarget.target_revenue;
      previousMargin = prevTarget.target_gross_margin;
    } catch (e) {
      // If no previous target, try to get actual revenue
      try {
        const firstDay = `${prevYear}-${String(prevMonth).padStart(2, '0')}-01`;
        const lastDay = new Date(prevYear, prevMonth, 0).toISOString().split('T')[0];
        const { data: metrics } = await api.get('/reports/dashboard', {
          params: { startDate: firstDay, endDate: lastDay }
        });
        previousRevenue = metrics.totalRevenue || 1000000;
        previousMargin = metrics.grossMargin || 35;
      } catch (e2) {
        // Ultimate fallback
        previousRevenue = 1000000;
        previousMargin = 35;
      }
    }
  }
  
  // Apply 10% growth
  const targetRevenue = Math.round(previousRevenue * 1.10);
  
  return {
    year,
    month,
    target_revenue: targetRevenue,
    target_gross_margin: previousMargin,
    target_cash_reserve_days: 30,
    max_outstanding_ratio: 20,
    default_staff_target_revenue: Math.round(targetRevenue / 20), // Rough estimate: 20 staff
    isAutoGenerated: true,
    basedOn: { year: prevYear, month: prevMonth, revenue: previousRevenue }
  };
};

