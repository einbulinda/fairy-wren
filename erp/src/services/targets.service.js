import api from "@/api";

// ==========================================
// BUSINESS TARGETS API
// ==========================================

/**
 * Get business targets for a specific month
 * Falls back to previous month + 10% if no target set
 */
export const fetchBusinessTarget = async (year, month) => {
  try {
    const { data } = await api.get(`/targets/business/${year}/${month}`);
    return data.data;
  } catch (error) {
    // If no target found, calculate fallback
    if (error.response?.status === 404) {
      return calculateFallbackTarget(year, month);
    }
    throw error;
  }
};

/**
 * Get or create business target with fallback logic
 */
export const getOrCreateBusinessTarget = async (year, month, fallbackRevenue = null) => {
  try {
    const { data } = await api.get(`/targets/business/${year}/${month}`);
    return data.data;
  } catch (error) {
    if (error.response?.status === 404) {
      // Calculate fallback: last month actual + 10%
      const fallback = await calculateFallbackTarget(year, month, fallbackRevenue);
      
      // Auto-create target with fallback values
      try {
        const { data } = await api.post('/targets/business', {
          year,
          month,
          target_revenue: fallback.target_revenue,
          target_gross_margin: fallback.target_gross_margin || 35,
          target_cash_reserve_days: fallback.target_cash_reserve_days || 30,
          default_staff_target_revenue: fallback.default_staff_target_revenue || 50000,
          auto_generated: true
        });
        return { ...data.data, isAutoGenerated: true };
      } catch (createError) {
        // If creation fails, return fallback without saving
        return { ...fallback, isAutoGenerated: true, isUnsaved: true };
      }
    }
    throw error;
  }
};

/**
 * Create or update business target
 */
export const saveBusinessTarget = async (targetData) => {
  const { year, month, ...data } = targetData;
  const { data: response } = await api.post('/targets/business', {
    year,
    month,
    ...data,
    auto_generated: false
  });
  return response.data;
};

