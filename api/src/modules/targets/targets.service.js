// DASHBOARD INTEGRATION
// ==========================================

exports.getDashboardTargets = async (year, month, currentMetrics = {}) => {
  // Get business target
  const businessTarget = await exports.getBusinessTarget(year, month);

  // Get user targets
  const userTargets = await exports.getAllUserTargets(year, month);

  // Build staff targets map
  const staffTargetsMap = {};
  for (const target of userTargets) {
    staffTargetsMap[target.user_id] = target;
  }

  // Calculate gaps
  const actualRevenue = currentMetrics.totalRevenue || 0;
  const targetRevenue = businessTarget.target_revenue || 0;
  const revenueGap = Math.max(0, targetRevenue - actualRevenue);

  const actualMargin = currentMetrics.grossMargin || 0;
  const targetMargin = businessTarget.target_gross_margin || 35;
  const marginGap = targetMargin - actualMargin;

  return {
    // Main targets
    targetRevenue,
    targetGrossMargin: targetMargin,
    targetCashReserveDays: businessTarget.target_cash_reserve_days || 30,
    targetOutstandingRatio: businessTarget.max_outstanding_ratio || 20,

    // Staff defaults
    defaultStaffTargetRevenue:
      businessTarget.default_staff_target_revenue || 50000,

    // Staff-specific targets
    staffTargetsMap,

    // Metadata
    isAutoGenerated: businessTarget.isAutoGenerated,

    // Calculated gaps
    revenueGap,
    marginGap,
  };
};

