// HELPER FUNCTIONS
// ==========================================

/**
 * Converts empty strings to null for numeric fields so the DB
 * doesn't receive invalid input (e.g. "" for a numeric column).
 */
function sanitizeNumeric(obj, fields) {
  const out = { ...obj };
  for (const field of fields) {
    if (out[field] === "" || out[field] === undefined) {
      out[field] = null;
    } else if (out[field] !== null) {
      out[field] = Number(out[field]) || null;
    }
  }
  return out;
}

async function calculateFallbackTarget(year, month) {
  // Calculate previous month
  let prevYear = year;
  let prevMonth = month - 1;
  if (prevMonth === 0) {
    prevMonth = 12;
    prevYear = year - 1;
  }

  // Get previous month's actual revenue
  const prevRevenue = await repo.getPreviousMonthRevenue(year, month);

  // Apply 10% growth
  const targetRevenue =
    prevRevenue > 0 ? Math.round(prevRevenue * 1.1) : 1000000;

  return {
    year,
    month,
    target_revenue: targetRevenue,
    target_gross_margin: 35,
    target_cash_reserve_days: 30,
    max_outstanding_ratio: 20,
    default_staff_target_revenue: Math.round(targetRevenue / 20), // Estimate: 20 staff
    target_avg_bill_value: null,
    target_bill_count: null,
    target_inventory_turnover: 4,
  };
}
