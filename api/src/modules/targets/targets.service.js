exports.getUserTarget = async (userId, year, month) => {
  const { data, error } = await repo.getUserTarget(userId, year, month);

  if (error && error.code !== "PGRST116") {
    throw new Error("FAILED_TO_FETCH_USER_TARGET");
  }

  if (!data) {
    // Return default target
    return {
      user_id: userId,
      year,
      month,
      target_revenue: 50000,
      target_bill_count: null,
      target_avg_bill_value: null,
      isDefault: true,
    };
  }

  return data;
};

exports.getAllUserTargets = async (year, month) => {
  const { data, error } = await repo.getAllUserTargets(year, month);

  if (error) {
    console.log("Error fetching users targets:", error);
    throw new Error("FAILED_TO_FETCH_USER_TARGETS");
  }

  return data || [];
};

exports.saveUserTarget = async (targetData, userId) => {
  const { user_id, year, month, ...data } = targetData;

  if (!user_id || !year || !month) {
    throw new Error("USER_YEAR_MONTH_REQUIRED");
  }

  const sanitized = sanitizeNumeric(data, [
    "target_revenue",
    "target_bill_count",
    "target_avg_bill_value",
  ]);

  const payload = {
    user_id,
    year,
    month,
    ...sanitized,
    updated_by: userId,
    created_by: userId,
  };

  const { data: saved, error } = await repo.upsertUserTarget(payload);

  if (error) {
    throw new Error("FAILED_TO_SAVE_USER_TARGET");
  }

  return saved;
};

