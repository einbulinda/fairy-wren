const repo = require("./targets.repository");

// ==========================================
// BUSINESS TARGETS SERVICE
// ==========================================

exports.getBusinessTarget = async (year, month) => {
  const { data, error } = await repo.getBusinessTarget(year, month);

  if (error && error.code !== "PGRST116") {
    // PGRST116 = no rows returned
    throw new Error("FAILED_TO_FETCH_BUSINESS_TARGET");
  }

  // If no target found, calculate fallback
  if (!data) {
    const fallbackTarget = await calculateFallbackTarget(year, month);
    return {
      ...fallbackTarget,
      isAutoGenerated: true,
    };
  }

  return data;
};

exports.getYearlyBusinessTargets = async (year) => {
  const { data, error } = await repo.getYearlyBusinessTargets(year);

  if (error) throw new Error("FAILED_TO_FETCH_YEARLY_TARGETS");

  // Fill in missing months with fallbacks
  const targetsMap = new Map(data?.map((t) => [t.month, t]) || []);
  const completeTargets = [];

  for (let month = 1; month <= 12; month++) {
    if (targetsMap.has(month)) {
      completeTargets.push(targetsMap.get(month));
    } else {
      const fallback = await calculateFallbackTarget(year, month);
      completeTargets.push({
        ...fallback,
        isAutoGenerated: true,
        isPlaceholder: true,
      });
    }
  }

  return completeTargets;
};

exports.saveBusinessTarget = async (targetData, userId) => {
  const { year, month, ...data } = targetData;

  if (!year || !month) {
    throw new Error("YEAR_AND_MONTH_REQUIRED");
  }

  const sanitized = sanitizeNumeric(data, [
    "target_revenue",
    "target_gross_margin",
    "target_cash_reserve_days",
    "max_outstanding_ratio",
    "default_staff_target_revenue",
    "target_avg_bill_value",
    "target_bill_count",
    "target_inventory_turnover",
  ]);

  const payload = {
    year,
    month,
    ...sanitized,
    updated_by: userId,
  };

  // Check if target exists
  const { data: existing } = await repo.getBusinessTarget(year, month);

  if (existing) {
    // Update
    const { data: updated, error } = await repo.updateBusinessTarget(
      existing.id,
      payload,
    );
    if (error) throw new Error("FAILED_TO_UPDATE_BUSINESS_TARGET");
    return updated;
  } else {
    // Insert
    payload.created_by = userId;
    const { data: created, error } = await repo.upsertBusinessTarget(payload);
    if (error) throw new Error("FAILED_TO_CREATE_BUSINESS_TARGET");
    return created;
  }
};

exports.bulkUpdateBusinessTargets = async (year, targets, userId) => {
  if (!Array.isArray(targets)) {
    throw new Error("INVALID_TARGETS_ARRAY");
  }

  const results = [];

  for (const target of targets) {
    const saved = await exports.saveBusinessTarget({ ...target, year }, userId);
    results.push(saved);
  }

  return results;
};

