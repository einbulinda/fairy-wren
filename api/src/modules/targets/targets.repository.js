const getSupabase = require("../../config/supabase");

// ==========================================
// BUSINESS TARGETS
// ==========================================

exports.getBusinessTarget = async (year, month) => {
  const supabase = getSupabase();
  return supabase
    .from("business_targets")
    .select("*")
    .eq("year", year)
    .eq("month", month)
    .single();
};

exports.getYearlyBusinessTargets = async (year) => {
  const supabase = getSupabase();
  return supabase
    .from("business_targets")
    .select("*")
    .eq("year", year)
    .order("month");
};

exports.upsertBusinessTarget = async (targetData) => {
  const supabase = getSupabase();
  return supabase
    .from("business_targets")
    .upsert(targetData, { onConflict: ["year", "month"] })
    .select()
    .single();
};

exports.updateBusinessTarget = async (id, updates) => {
  const supabase = getSupabase();
  return supabase
    .from("business_targets")
    .update(updates)
    .eq("id", id)
    .select()
    .single();
};

